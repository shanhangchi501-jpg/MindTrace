    val all: List<DiagnosisDef> = icd10 + icd11 + dsm5

    fun standardLabel(standard: String, english: Boolean): String = when (standard) {
        "ICD10" -> "ICD-10"
        "ICD11" -> "ICD-11"
        "DSM5" -> "DSM-5"
        else -> if (english) "Custom" else "自定义"
    }

    fun search(standard: String, query: String): List<DiagnosisDef> {
        val source = when (standard) {
            "ICD10" -> icd10
            "ICD11" -> icd11
            "DSM5" -> dsm5
            else -> emptyList()
        }
        val q = query.trim()
        if (q.isBlank()) return source
        return source.filter {
            it.code.contains(q, ignoreCase = true) ||
                it.name.contains(q, ignoreCase = true) ||
                it.nameEn.contains(q, ignoreCase = true)
        }
    }

    fun statusLabel(status: String, english: Boolean): String = when (status) {
        "suspected" -> if (english) "Suspected" else "疑似"
        "remission" -> if (english) "In remission" else "已缓解"
        "history" -> if (english) "History" else "既往诊断"
        else -> if (english) "Confirmed" else "已确诊"
    }

    private fun d10(code: String, name: String, nameEn: String) =
        DiagnosisDef("ICD10", code, name, nameEn)

    private fun d11(code: String, name: String, nameEn: String) =
        DiagnosisDef("ICD11", code, name, nameEn)

    private fun d5(name: String, nameEn: String) =
        DiagnosisDef("DSM5", "", name, nameEn)
