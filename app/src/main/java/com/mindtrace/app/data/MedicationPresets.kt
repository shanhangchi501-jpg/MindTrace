    /** 中英切名：按任一语言的通用名匹配预设，切回另一种语言时不留原文。 */
    fun localizedName(stored: String, english: Boolean): String {
        val trimmed = stored.trim()
        if (trimmed.isEmpty()) return stored
        val match = all.firstOrNull {
            it.zh == trimmed || it.en.equals(trimmed, ignoreCase = true)
        } ?: return stored
        return if (english) match.en else match.zh
    }

    /** 输入联想：空查询时给常用药，否则按中英文子串过滤。 */
    fun suggestions(query: String, english: Boolean, limit: Int = 200): List<DrugPreset> {
        val q = query.trim()
        if (q.isEmpty()) return all.take(limit)
        return all.filter {
            it.zh.contains(q) || it.en.contains(q, ignoreCase = true)
        }.take(limit)
    }
