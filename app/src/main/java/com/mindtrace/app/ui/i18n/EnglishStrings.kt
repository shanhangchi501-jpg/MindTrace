    fun translateDynamic(text: String): String {
        for ((regex, build) in rules) {
            val match = regex.find(text) ?: continue
            var result = build(match)
            // 规则里用 \$1…\$9 表示捕获组；这里手动填入实际内容。
            for (index in 1..9) {
                val raw = match.groupValues.getOrNull(index) ?: ""
                // 捕获组本身也可能是固定词条（如“过去两周”），先翻译再填入。
                result = result.replace("\$$index", entries[raw] ?: raw)
            }
            return result
        }
        return text
    }
